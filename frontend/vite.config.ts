import { defineConfig, loadEnv } from 'vite';
import react from '@vitejs/plugin-react';

export default defineConfig(({ mode }) => {
  // Адрес бэкенда берём из .env, а не из process.env: так конфигурация
  // одного проекта живёт в одном месте и не требует типов Node.
  const env = loadEnv(mode, '.', 'VITE_');

  return {
    plugins: [react()],
    server: {
      port: 5173,
      // Слушаем именно 127.0.0.1: на Windows «localhost» сначала пробуется
      // по IPv6, и разрешение имени добавляет к каждому запросу заметную
      // задержку — на замерах это секунды на пустом месте.
      host: '127.0.0.1',
      // Бэкенд живёт на 8000. Прокси нужен, чтобы фронтенд ходил в /api/v1
      // одинаково и с моками, и без них — без правки кода.
      //
      // С появлением входа у прокси стало второе, более важное назначение:
      // токен сессии ездит в куке HttpOnly, а `Access-Control-Allow-Origin: *`
      // вместе с учётными данными запрещён самим стандартом. Через прокси
      // страница и API — один источник: кука ставится и уезжает обратно сама,
      // CORS не участвует вовсе, а SameSite=Lax работает как задумано.
      // Обращение напрямую к 127.0.0.1:8000 тоже возможно, но требует точного
      // списка в CORS_ORIGINS бэкенда (там он уже прописан:
      // http://127.0.0.1:5173,http://localhost:5173).
      //
      // Цель прокси — 127.0.0.1, а не localhost, по той же причине, что и host.
      proxy: {
        '/api': {
          target: env.VITE_PROXY_TARGET || 'http://127.0.0.1:8000',
          changeOrigin: true,
        },
      },
    },
  };
});
