"""Телефон в одном виде на всю систему.

Схема требует E.164 (`person.phone`, `lead.phone` проверены регулярным
выражением), а приходит номер как угодно: бот отдаёт «8 701 555 33 22»,
администратор набирает «+7 (701) 555-24-18», форма сайта — «77015553322».
Это один человек, и три записи вместо одной означают потерянную семейную
скидку, дубль в воронке и разъехавшуюся историю платежей.

Знание «восьмёрка — это тот же +7» живёт здесь одно на всех: и поиск
по плательщику, и приём заявки по вебхуку, и конверсия в ученика.
"""
from __future__ import annotations

import re

# То же ограничение, что в схеме: db/001_core.sql, person.phone.
E164 = re.compile(r"^\+[1-9][0-9]{7,14}$")

# Длина казахстанского и российского номера с кодом страны.
_CIS_LENGTH = 11
# Национальный номер без кода страны: 701 555 24 18.
_NATIONAL_LENGTH = 10


def digits_of(value: str) -> str:
    """Цифры номера, приведённые к виду с кодом страны 7.

    Восьмёрка в начале — казахстанский код выхода на межгород, тот же номер,
    что и +7. Без этой замены поиск по продиктованному номеру не находил бы
    ничего, а вебхук заводил бы второго лида на того же человека.
    """
    digits = re.sub(r"\D", "", value or "")
    if len(digits) == _CIS_LENGTH and digits.startswith("8"):
        return "7" + digits[1:]
    if len(digits) == _NATIONAL_LENGTH:
        return "7" + digits
    return digits


def normalize(value: str | None) -> str | None:
    """Номер в E.164 или None, если это не похоже на телефон.

    None вместо исключения намеренно: заявку с кривым номером принимаем
    и показываем администратору — он перезвонит по тому, что записано
    в комментарии. Потерять лид из-за формата номера дороже, чем принять
    его без телефона.
    """
    if not value:
        return None
    digits = digits_of(value)
    candidate = f"+{digits}"
    return candidate if E164.match(candidate) else None
