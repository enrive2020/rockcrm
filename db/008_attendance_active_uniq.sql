-- ============================================================================
-- RockCRM · 008 · Действующая отметка одна, отменённые не мешают
--
-- Отмена отметки — компенсация, а не удаление: строка остаётся в базе
-- с проставленным revoked_at, потому что за ней стоят записи в журнале
-- абонемента и в зарплате. Сплошной UNIQUE (lesson_id, student_id)
-- между действующей и отменённой разницы не делал, поэтому администратор,
-- ошибившийся учеником, оставался с неотмечаемым занятием навсегда:
-- отменить мог, а поставить правильную отметку — уже нет.
--
-- Частичный индекс снимает тупик, не трогая принцип: действующая отметка
-- на паре «занятие + ученик» по-прежнему ровно одна.
--
-- Снимается именно ОГРАНИЧЕНИЕ, а не индекс: UNIQUE создаёт constraint,
-- и DROP INDEX на нём падает с «cannot drop index … because constraint …
-- requires it».
-- ============================================================================

ALTER TABLE attendance DROP CONSTRAINT attendance_lesson_id_student_id_key;

CREATE UNIQUE INDEX attendance_active_uniq
  ON attendance (lesson_id, student_id) WHERE revoked_at IS NULL;
