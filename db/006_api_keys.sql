-- ============================================================================
-- RockCRM · 006 · Ключи для внешних источников заявок
--
-- Заявки приходят из Telegram-бота, формы сайта и LeadHub — то есть от систем,
-- а не от людей. Заголовки X-Tenant-Id и X-User-Id для этого не годятся:
-- они заглушка внутренней авторизации, их знает кто угодно, и подставить
-- чужую школу было бы тривиально.
-- ============================================================================

CREATE TABLE api_key (
  id           uuid PRIMARY KEY DEFAULT uuid_v7(),
  tenant_id    uuid NOT NULL REFERENCES tenant(id) ON DELETE CASCADE,
  name         text NOT NULL,          -- «Telegram-бот», «Форма на сайте», «LeadHub»

  -- Ключ хранится хешем, как пароль: утечка базы не должна давать
  -- возможность слать заявки от имени школы. Открытый текст показывается
  -- один раз при создании и больше не восстанавливается.
  key_hash     text NOT NULL UNIQUE,
  -- Первые символы — чтобы человек мог опознать ключ в списке
  -- и понять, какой именно отзывает.
  prefix       text NOT NULL,

  -- Что ключу позволено. Ключ бота умеет только заводить заявки и не должен
  -- получать доступ к деньгам, если однажды утечёт в чат.
  scopes       text[] NOT NULL DEFAULT ARRAY['leads:write'],

  last_used_at timestamptz,
  revoked_at   timestamptz,
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX api_key_tenant ON api_key (tenant_id) WHERE revoked_at IS NULL;

COMMENT ON TABLE api_key IS
  'Ключи внешних источников заявок. Ищутся по хешу до того, как известен тенант.';

-- ---------------------------------------------------------------------------
-- Политики уровня строк здесь неприменимы — по той же причине, что и у таблицы
-- тенантов: приложение ищет ключ по хешу ИМЕННО ЗАТЕМ, чтобы узнать тенанта.
-- Политика на current_tenant() отсекла бы строку раньше, чем тенант станет
-- известен, и аутентификация внешних источников стала бы невозможной.
--
-- Защита строится правами: приложение может читать и отмечать использование,
-- но не создавать и не отзывать ключи — это делает владелец школы через
-- административный канал.
-- ---------------------------------------------------------------------------
GRANT SELECT ON api_key TO rockcrm_app;
GRANT UPDATE (last_used_at) ON api_key TO rockcrm_app;
REVOKE INSERT, DELETE ON api_key FROM rockcrm_app;
