-- ============================================================================
-- RockCRM · 007 · Индекс поиска пробного урока по заявке
--
-- Занятие ссылается на заявку через lead_id, но индекса по нему не было:
-- карточка заявки и назначение пробного платили полным проходом по таблице
-- занятий. На демонстрационных данных это незаметно, на полугодовой истории
-- в четыре тысячи занятий — уже нет.
--
-- Частичный: заполненный lead_id есть только у пробных уроков, а это доли
-- процента строк. Индексировать ради них всю таблицу незачем.
-- ============================================================================

CREATE INDEX lesson_lead ON lesson (lead_id, starts_at DESC)
  WHERE lead_id IS NOT NULL;
